#!/usr/bin/env node
/**
 * Offline migration generator.
 *
 * The Prisma CLI normally shells out to a schema engine binary to diff a
 * schema. Some sandboxed environments forbid the pipe setup that requires.
 * This script uses the in-process DMMF (WASM) to emit an equivalent initial
 * migration, which is then checked in and applied with `prisma migrate deploy`
 * in every real environment.
 *
 * Usage: node scripts/generate-migration.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import prismaInternals from "@prisma/internals";

const { getDMMF } = prismaInternals;

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const schemaPath = join(root, "packages/database/prisma/schema.prisma");
const outPath = join(
  root,
  "packages/database/prisma/migrations/20260101000000_init/migration.sql",
);

const datamodel = readFileSync(schemaPath, "utf8");

const dmmf = await getDMMF({ datamodel });

const scalarSql = {
  String: "TEXT",
  Int: "INTEGER",
  Float: "DOUBLE PRECISION",
  Boolean: "BOOLEAN",
  DateTime: "TIMESTAMP(3)",
  Json: "JSONB",
  BigInt: "BIGINT",
  Decimal: "DECIMAL(65,30)",
  Bytes: "BYTEA",
};

const q = (s) => `"${s}"`;

const referentialAction = {
  Cascade: "CASCADE",
  Restrict: "RESTRICT",
  NoAction: "NO ACTION",
  SetNull: "SET NULL",
  SetDefault: "SET DEFAULT",
};

function defaultClause(field) {
  if (!field.hasDefaultValue) return "";
  const d = field.default;
  if (d === null || d === undefined) return "";

  // Prisma's DMMF returns primitives directly for literal defaults.
  if (typeof d === "boolean") return ` DEFAULT ${d}`;
  if (typeof d === "number") return ` DEFAULT ${d}`;
  if (Array.isArray(d)) {
    const base = scalarSql[field.type] ?? "TEXT";
    return ` DEFAULT ARRAY[]::${base}[]`;
  }

  const name = typeof d === "string" ? d : d?.name;
  if (name === undefined) return "";

  switch (name) {
    case "now":
      return " DEFAULT CURRENT_TIMESTAMP";
    case "autoincrement":
    case "cuid":
    case "uuid":
    case "ulid":
    case "nanoid":
    case "dbgenerated":
      // Generated by the client (or by the database outside Prisma).
      return "";
    case "[]":
      return field.isList
        ? ` DEFAULT ARRAY[]::${scalarSql[field.type] ?? "TEXT"}[]`
        : field.type === "Json"
          ? " DEFAULT '[]'::jsonb"
          : "";
    case "null":
      return "";
    default: {
      if (field.kind === "enum") return ` DEFAULT '${name}'`;
      if (field.type === "Json") return ` DEFAULT '${name}'::jsonb`;
      if (field.type === "String") return ` DEFAULT '${name}'`;
      if (field.type === "Int" || field.type === "Float") return ` DEFAULT ${name}`;
      return "";
    }
  }
}

function columnSql(field) {
  let type;
  if (field.kind === "enum") type = q(field.type);
  else type = scalarSql[field.type] ?? "TEXT";
  if (field.isList) type += "[]";
  const notNull = field.isRequired && !field.isList ? " NOT NULL" : "";
  return `    ${q(field.name)} ${type}${notNull}${defaultClause(field)}`;
}

const lines = [];
lines.push("-- LeadForge initial schema");
lines.push("-- Generated from packages/database/prisma/schema.prisma.");
lines.push("-- Apply with `prisma migrate deploy` (production) or `pnpm db:deploy`.");
lines.push("");

for (const e of dmmf.datamodel.enums) {
  const values = e.values.map((v) => `'${v.name}'`).join(", ");
  lines.push(`CREATE TYPE ${q(e.name)} AS ENUM (${values});`);
}
lines.push("");

for (const model of dmmf.datamodel.models) {
  const table = model.dbName ?? model.name;
  const cols = model.fields.filter((f) => f.kind !== "object").map(columnSql);
  const pkFields = model.primaryKey?.fields ?? model.fields.filter((f) => f.isId).map((f) => f.name);
  if (pkFields.length) {
    cols.push(`    PRIMARY KEY (${pkFields.map(q).join(", ")})`);
  }
  lines.push(`CREATE TABLE ${q(table)} (`);
  lines.push(cols.join(",\n"));
  lines.push(");");
  lines.push("");
}

// Unique constraints
const emittedUnique = new Set();
for (const model of dmmf.datamodel.models) {
  const table = model.dbName ?? model.name;
  const addUnique = (name, fields) => {
    const key = `${table}:${fields.join(",")}`;
    if (emittedUnique.has(key)) return;
    emittedUnique.add(key);
    lines.push(`CREATE UNIQUE INDEX ${q(name)} ON ${q(table)} (${fields.map(q).join(", ")});`);
  };
  for (const field of model.fields) {
    if (field.isUnique && field.kind !== "object") {
      addUnique(`${table}_${field.name}_key`, [field.name]);
    }
  }
  for (const idx of model.uniqueIndexes ?? []) {
    addUnique(idx.name ?? `${table}_${idx.fields.join("_")}_key`, idx.fields);
  }
  for (const fields of model.uniqueFields ?? []) {
    addUnique(`${table}_${fields.join("_")}_key`, fields);
  }
}
lines.push("");

// Foreign keys, after all tables exist.
for (const model of dmmf.datamodel.models) {
  const table = model.dbName ?? model.name;
  for (const field of model.fields) {
    if (field.kind !== "object") continue;
    const from = field.relationFromFields ?? [];
    const to = field.relationToFields ?? [];
    if (!from.length || !to.length) continue;
    const refTable = field.type;
    const name = `${table}_${from.join("_")}_fkey`;
    const onDelete = field.relationOnDelete ? ` ON DELETE ${referentialAction[field.relationOnDelete] ?? "NO ACTION"}` : "";
    const onUpdate = field.relationOnUpdate
      ? ` ON UPDATE ${referentialAction[field.relationOnUpdate] ?? "CASCADE"}`
      : " ON UPDATE CASCADE";
    lines.push(
      `ALTER TABLE ${q(table)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${from
        .map(q)
        .join(", ")}) REFERENCES ${q(refTable)}(${to.map(q).join(", ")})${onDelete}${onUpdate};`,
    );
  }
}
lines.push("");

// Secondary indexes
for (const model of dmmf.datamodel.models) {
  const table = model.dbName ?? model.name;
  for (const idx of model.indexes ?? []) {
    const name = idx.name ?? `${table}_${idx.fields.map((f) => f.name).join("_")}_idx`;
    const cols = idx.fields
      .map((f) => `${q(f.name)}${f.sort === "Desc" ? " DESC" : ""}`)
      .join(", ");
    lines.push(`CREATE INDEX ${q(name)} ON ${q(table)} (${cols});`);
  }
}
lines.push("");

const sql = lines.join("\n");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, sql, "utf8");
console.log(`wrote ${outPath} (${sql.split("\n").length} lines, ${dmmf.datamodel.models.length} tables)`);
